/// A method name with the schema definitions of its parameters and result.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MethodSchema {
    pub method: &'static str,
    pub params: Option<&'static str>,
    pub result: &'static str,
}

impl MethodSchema {
    const fn new(method: &'static str, params: Option<&'static str>, result: &'static str) -> Self {
        Self {
            method,
            params,
            result,
        }
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn the_version_matches_the_release_pin() {
        let pin = include_str!("../../../deploy/codex-release.env");
        assert!(
            pin.lines()
                .any(|line| line == format!("CODEX_VERSION={}", super::CODEX_VERSION)),
            "deploy/codex-release.env pins a different Codex version"
        );
        assert!(
            super::SCHEMA_BUNDLE.starts_with('{'),
            "the vendored schema bundle is present"
        );
    }
}
