//! A minimal JSON-RPC client for `codex app-server` over stdio.
//!
//! The client covers only the methods Bokkie uses. Every type in
//! [`protocol`] is checked in tests against the JSON schema that the pinned
//! Codex version generates with
//! `codex app-server generate-json-schema --experimental`, vendored under
//! `schema/codex-<version>/`.
//!
//! The wire format is newline-delimited JSON. Like the app server itself,
//! messages omit the `"jsonrpc": "2.0"` member.

pub mod client;
pub mod protocol;
pub mod rpc;

pub use client::{AppServer, AppServerCommand, Client, Incoming};
pub use rpc::{Error, RequestId, RpcError};

/// The exact Codex release this crate is checked against.
pub const CODEX_VERSION: &str = "0.163.0";

/// The schema bundle generated by [`CODEX_VERSION`] with
/// `codex app-server generate-json-schema --experimental`.
pub const SCHEMA_BUNDLE: &str =
    include_str!("../schema/codex-0.163.0/codex_app_server_protocol.schemas.json");

